// Records every version of QRdx's official frames, so an image URL that
// names a frame's version (autumn-maple.v1, as the editor's Get code copies
// it) draws the same image for as long as the URL is used.
//
//   bun run --filter app frames:versions           record what's new
//   bun run --filter app frames:versions --check   exit 1 if anything is
//
// Run it whenever an official frame is added or its spec changes
// (packages/qrdx/src/frames/official/<id>.json). The frames generator
// (packages/qrdx/scripts/official-frames/write.mjs) runs it after writing,
// and tests/frames/frame-versions.test.ts fails until it has run.
//
// It only appends: a frame whose current spec isn't its latest recorded
// version gets the next version, a new frame gets v1. Nothing recorded is
// ever changed or removed, a withdrawn frame's versions included, since
// image URLs out in the world still name them. It writes
// lib/frames/versions/record.json (every version with its spec and
// frameSpecHash, read by the image API only) and lib/frames/versions/
// latest.ts (each frame's latest version above v1, for the browser).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { isDeepStrictEqual } from "node:util";
import { OFFICIAL_FRAME_LIST } from "../../../packages/qrdx/src/frames/catalogue/all";
import { frameSpecHash } from "../../../packages/qrdx/src/frames/spec-hash";
import type { FrameSpec } from "../../../packages/qrdx/types/frame-spec";

interface FrameVersion {
  v: number;
  hash: string;
  spec: FrameSpec;
}
type FrameVersionRecord = Record<string, FrameVersion[]>;

const dir = new URL("../lib/frames/versions/", import.meta.url);
const recordFile = new URL("record.json", dir);
const latestFile = new URL("latest.ts", dir);
const check = process.argv.includes("--check");

const record: FrameVersionRecord = existsSync(recordFile)
  ? JSON.parse(readFileSync(recordFile, "utf8"))
  : {};

// What's recorded must be as it was published: refuse to touch a record
// that isn't, rather than "fix" it.
const broken: string[] = [];
for (const [id, versions] of Object.entries(record)) {
  versions.forEach((version, index) => {
    if (version.v !== index + 1) {
      broken.push(`${id}: version ${index + 1} is numbered ${version.v}`);
    } else if (frameSpecHash(version.spec) !== version.hash) {
      broken.push(`${id}.v${version.v}: its spec no longer matches its hash`);
    }
  });
}
if (broken.length > 0) {
  console.error(
    `The frame version record has been changed by hand (or merged by keeping both sides):\n  ${broken.join("\n  ")}\nTake the published record (git checkout origin/staging -- apps/app/lib/frames/versions/record.json apps/app/lib/frames/versions/latest.ts), then run this again: it adds your changes after its versions.`,
  );
  process.exit(1);
}

const added: string[] = [];
for (const frame of OFFICIAL_FRAME_LIST) {
  const hash = frameSpecHash(frame.spec);
  const versions = record[frame.id] ?? [];
  const latest = versions.at(-1);
  if (latest?.hash === hash && isDeepStrictEqual(latest.spec, frame.spec)) {
    continue;
  }
  // A changed spec, or one changed back to an earlier version's: either
  // way the next version, so the latest is always the last.
  const v = versions.length + 1;
  record[frame.id] = [...versions, { v, hash, spec: frame.spec }];
  added.push(`${frame.id}.v${v}`);
}

/** One line per version, frames by id: appending a version adds a line. */
function recordJson(versions: FrameVersionRecord): string {
  const frames = Object.keys(versions)
    .sort()
    .map((id) => {
      const lines = (versions[id] ?? []).map(
        (version) =>
          `    ${JSON.stringify({ v: version.v, hash: version.hash, spec: version.spec })}`,
      );
      return `  ${JSON.stringify(id)}: [\n${lines.join(",\n")}\n  ]`;
    });
  return `{\n${frames.join(",\n")}\n}\n`;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function latestTs(versions: FrameVersionRecord): string {
  const above = Object.keys(versions)
    .sort()
    .filter((id) => (versions[id]?.length ?? 0) > 1)
    .map(
      (id) =>
        `  ${IDENTIFIER.test(id) ? id : JSON.stringify(id)}: ${versions[id]?.length},`,
    );
  const map = above.length === 0 ? "{}" : `{\n${above.join("\n")}\n}`;
  return `// Generated by scripts/frame-versions.ts from record.json: run
// \`bun run --filter app frames:versions\`, never edit by hand.

/**
 * The latest version of each official frame QRdx has changed since it was
 * first published; every other frame is at v1. The browser pins the frames
 * it copies with these (./names.ts) and never holds an older spec.
 */
export const LATEST_FRAME_VERSIONS: Readonly<Record<string, number>> = ${map};
`;
}

const nextRecord = recordJson(record);
const nextLatest = latestTs(record);
const stale = [
  ...(existsSync(recordFile) && readFileSync(recordFile, "utf8") === nextRecord
    ? []
    : ["record.json"]),
  ...(existsSync(latestFile) && readFileSync(latestFile, "utf8") === nextLatest
    ? []
    : ["latest.ts"]),
];

if (check) {
  if (stale.length > 0) {
    console.error(
      `Official frame versions to record: ${added.length > 0 ? added.join(", ") : "none"}; out of date: ${stale.join(", ")}. Run bun run --filter app frames:versions`,
    );
    process.exit(1);
  }
  console.log(
    `${OFFICIAL_FRAME_LIST.length} official frames, every version recorded.`,
  );
} else {
  if (stale.includes("record.json")) writeFileSync(recordFile, nextRecord);
  if (stale.includes("latest.ts")) writeFileSync(latestFile, nextLatest);
  console.log(
    added.length > 0
      ? `Recorded ${added.length} new version(s): ${added.slice(0, 20).join(", ")}${added.length > 20 ? ", …" : ""}`
      : "No new frame versions.",
  );
}
