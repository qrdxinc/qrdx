// Writes the generated seed files in packages/database/scripts:
// - community-seed-presets.json: the built-in themes the community seed
//   publishes as official @qrdx themes (./preset-themes.ts);
// - community-seed-designs.json: the official designs made for the
//   gallery (./designs/index.ts).
// Run after changing one of those presets in utils/qr-presets.ts, a
// description, or a design:
//
//   cd apps/app && bun x tsx scripts/community-seed/generate.ts
//
// tests/database/seed-community.test.ts and seed-designs.test.ts fail
// while a file is stale. The designs' gate scores (community-seed-design-
// scores.json, stored as scan_score by the seed) are written by the design
// test, since they need the server's scorer:
//
//   cd apps/app && UPDATE_COMMUNITY_SEED_SCORES=1 bun x vitest run tests/database/seed-designs.test.ts
// It only reads the presets and designs and writes
// the files: nothing connects to a database. Items already seeded never
// change (published versions are immutable), so an edit here only reaches
// a theme that isn't seeded yet.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSeedDesigns } from "./designs";
import { buildPresetSeedThemes } from "./preset-themes";

const root = join(__dirname, "..", "..");
const scripts = join(root, "..", "..", "packages", "database", "scripts");
const PRESETS_OUT = join(scripts, "community-seed-presets.json");
const DESIGNS_OUT = join(scripts, "community-seed-designs.json");
const ultracitePath = join(
  root,
  "..",
  "..",
  "node_modules",
  ".bin",
  "ultracite",
);

const themes = buildPresetSeedThemes();
writeFileSync(
  PRESETS_OUT,
  `${JSON.stringify(
    {
      note: "Generated by apps/app/scripts/community-seed/generate.ts from apps/app/utils/qr-presets.ts. Don't edit by hand.",
      themes,
    },
    null,
    2,
  )}\n`,
);

const designs = buildSeedDesigns();
writeFileSync(
  DESIGNS_OUT,
  `${JSON.stringify(
    {
      note: "Generated by apps/app/scripts/community-seed/generate.ts from apps/app/scripts/community-seed/designs. Don't edit by hand.",
      themes: designs,
    },
    null,
    2,
  )}\n`,
);

// Keep the files as `ultracite check` expects them.
const fixed = spawnSync(ultracitePath, ["fix", PRESETS_OUT, DESIGNS_OUT], {
  cwd: root,
  stdio: "inherit",
});
if (fixed.status !== 0) {
  throw new Error("ultracite fix failed on the generated seed files");
}
console.log(`Wrote ${themes.length} themes to ${PRESETS_OUT}`);
console.log(`Wrote ${designs.length} designs to ${DESIGNS_OUT}`);
