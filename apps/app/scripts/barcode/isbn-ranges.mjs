// Writes lib/barcode/isbn-ranges.generated.ts: where the hyphens go in an
// ISBN, from the International ISBN Agency's range message. The generator
// prints the ISBN above the bars with its hyphens (ISBN Users' Manual, 8.2),
// and only the ranges say how long each element is.
//
// Run now and then (the agency adds ranges as it gives them out):
//   node scripts/barcode/isbn-ranges.mjs                   # downloads it
//   node scripts/barcode/isbn-ranges.mjs RangeMessage.xml  # a saved copy
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://www.isbn-international.org/export_rangemessage.xml";
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../lib/barcode/isbn-ranges.generated.ts",
);

const file = process.argv[2];
const xml = file
  ? readFileSync(file, "utf8")
  : await fetch(SOURCE).then((response) => {
      if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
      return response.text();
    });

const date = new Date(
  /<MessageDate>([^<]+)<\/MessageDate>/.exec(xml)?.[1] ?? "",
);
if (Number.isNaN(date.getTime())) throw new Error("No MessageDate");

const blocks = [
  ...xml.matchAll(
    /<(?:EAN\.UCC|Group)>\s*<Prefix>([\d-]+)<\/Prefix>\s*<Agency>[^<]*<\/Agency>\s*<Rules>([\s\S]*?)<\/Rules>/g,
  ),
];
if (blocks.length < 200) throw new Error(`Only ${blocks.length} prefixes`);

const pad = (n) => String(n).padStart(7, "0");

/**
 * A block's rules as "<end><length>", in order. Ranges the message leaves
 * out (a gap before the first, between two or after the last) are written
 * as not given out (length 0), so every block runs 0000000 to 9999999.
 */
function encode(prefix, body) {
  const rules = [
    ...body.matchAll(
      /<Range>(\d{7})-(\d{7})<\/Range>\s*<Length>(\d)<\/Length>/g,
    ),
  ].map((match) => ({
    start: Number(match[1]),
    end: Number(match[2]),
    length: Number(match[3]),
  }));
  if (rules.length === 0) throw new Error(`${prefix}: no rules`);
  const out = [];
  let next = 0;
  for (const rule of rules) {
    if (rule.start < next) throw new Error(`${prefix}: ranges overlap`);
    if (rule.start > next) out.push({ end: rule.start - 1, length: 0 });
    out.push(rule);
    next = rule.end + 1;
  }
  if (next <= 9_999_999) out.push({ end: 9_999_999, length: 0 });
  return out
    .map((rule) => `${pad(rule.end).replace(/9+$/, "")}${rule.length}`)
    .join(",");
}

const entries = blocks.map(([, prefix, body]) => [
  prefix,
  encode(prefix, body),
]);
const day = date.toISOString().slice(0, 10);

/** One entry as the formatter lays it out: on two lines past 80 columns. */
const entry = (prefix, rules) => {
  const line = `  "${prefix}": "${rules}",`;
  return line.length > 80 ? `  "${prefix}":\n    "${rules}",` : line;
};

writeFileSync(
  OUT,
  `// Generated by scripts/barcode/isbn-ranges.mjs from the International ISBN
// Agency's range message (${SOURCE}),
// dated ${day}. Don't edit by hand: run the script again to update it.
//
// Each entry is a prefix (978, 979) or registration group (978-0, 979-10…)
// and its ranges in order, as "<end><length>": the range ends at <end>
// padded to 7 digits with 9s, and the next element in it is <length> digits
// long (0: not given out yet). Each range starts where the last one ended,
// the first at 0000000.

/** The day the range message was issued (YYYY-MM-DD). */
export const ISBN_RANGES_DATE = "${day}";

export const ISBN_RANGES: Record<string, string> = {
${entries.map(([prefix, rules]) => entry(prefix, rules)).join("\n")}
};
`,
);
console.log(`Wrote ${entries.length} prefixes and groups (${day}) to ${OUT}`);
