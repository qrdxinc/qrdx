/**
 * Writes the pages. `server` is the fumadocs-openapi server of the document
 * (generate.ts), `output` the content folder.
 */
export async function writeReferencePages(
  document: OpenAPIV3_1.Document,
  server: import("fumadocs-openapi/server").OpenAPIServer,
  output: string,
): Promise<number> {
  const { generateFiles } = await import("fumadocs-openapi");
  const operations = operationsOf(document);
  const byId = new Map(
    operations.map((operation) => [operation.id, operation]),
  );

  // Pages of removed operations go too: delete everything we generated.
  mkdirSync(output, { recursive: true });
  for (const file of readdirSync(output)) {
    const path = join(output, file);
    if (
      file.endsWith(".mdx") &&
      readFileSync(path, "utf8").includes("openapi:generate")
    ) {
      rmSync(path);
    }
  }

  await generateFiles({
    input: server,
    output,
    per: "operation",
    includeDescription: false,
    addGeneratedComment: GENERATED_NOTE,
    frontmatter: (_title, description) => ({
      description: plainLead(description ?? ""),
    }),
    beforeWrite(files) {
      for (const file of files) {
        const id = file.path.replace(/\.mdx$/, "");
        const operation = byId.get(id);
        if (!operation) throw new Error(`No operation for ${file.path}`);
        file.path = `${operation.slug}.mdx`;
        const body = details(operation.description);
        if (body) {
          file.content = file.content.replace(
            "\n\nexport default function Layout",
            `\n\n${body}\n\nexport default function Layout`,
          );
        }
      }
    },
  });

  writeFileSync(join(output, "index.mdx"), indexPage(document, operations));

  writeFileSync(
    join(output, "meta.json"),
    `${JSON.stringify(metaJson(document, operations), null, 2)}\n`,
  );
  return operations.length;
}

/** The section's meta.json: the endpoints grouped by tag, in document order. */
export function metaJson(
  document: OpenAPIV3_1.Document,
  operations: OperationInfo[],
) {
  // index.mdx is the folder's own page (the "API reference" link itself).
  const pages: string[] = [];
  for (const tag of document.tags ?? []) {
    const slugs = operations
      .filter((operation) => operation.tag === tag.name)
      .map((operation) => operation.slug);
    if (slugs.length > 0) pages.push(`---${tag.name}---`, ...slugs);
  }
  return {
    $schema: "../../../../.source/json-schema/docs.meta.json",
    title: "API reference",
    icon: "FileCode",
    pages,
  };
}

